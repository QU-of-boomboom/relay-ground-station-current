// Retained platform reset registers from the retired camera address window.
// GP writes are already joined by the official gp_io/gp0_manager chain.
module gs_platform_control (
    input wire i_clk,
    input wire i_bus_rst,
    input wire i_sys_rst_n,
    input wire [31:0] i_wr_addr,
    input wire [31:0] i_wr_data,
    input wire i_wr_valid,
    output wire o_wr_ready,
    input wire [31:0] i_rd_addr,
    input wire i_rd_valid,
    output wire o_rd_ready,
    output reg [31:0] o_rd_data,
    output reg o_rd_valid,
    input wire i_rd_ready,
    output reg o_soft_rst
);
    reg [31:0] reg_reset_count;
    reg flag_reset_finished;
    wire flag_reset_write;

    // The former mna_gp2axi adapter decoded only address bits [8:0].
    assign flag_reset_write = i_wr_valid && (i_wr_addr[8:0] == 9'h070);
    assign o_wr_ready = 1'b1;
    assign o_rd_ready = !i_bus_rst && !o_rd_valid;

    // Preserve the original platform reset pulse, including repeated writes.
    // Bus reset must not cancel this counter: it is generated by this pulse.
    always @(posedge i_clk) begin
        if (!i_sys_rst_n) o_soft_rst <= 1'b0;
        else if (flag_reset_write) o_soft_rst <= i_wr_data[0];
        else if (reg_reset_count == 32'd100) o_soft_rst <= 1'b0;
    end
    always @(posedge i_clk) begin
        if (!i_sys_rst_n) reg_reset_count <= 32'd0;
        else if (reg_reset_count == 32'd100) reg_reset_count <= 32'd0;
        else if (o_soft_rst) reg_reset_count <= reg_reset_count + 32'd1;
    end
    always @(posedge i_clk) begin
        if (!i_sys_rst_n) flag_reset_finished <= 1'b0;
        else if (flag_reset_write) flag_reset_finished <= 1'b0;
        else if (reg_reset_count == 32'd100) flag_reset_finished <= 1'b1;
    end

    // One response slot. Backpressure cannot overwrite the accepted data.
    // Retired video registers return GSNA instead of pretending to be a camera.
    always @(posedge i_clk) begin
        if (i_bus_rst) begin
            o_rd_valid <= 1'b0;
            o_rd_data <= 32'd0;
        end else if (i_rd_valid && o_rd_ready) begin
            o_rd_valid <= 1'b1;
            case (i_rd_addr[8:0])
                9'h070: o_rd_data <= {31'd0, o_soft_rst};
                9'h074: o_rd_data <= {31'd0, flag_reset_finished};
                default: o_rd_data <= 32'h47534e41;
            endcase
        end else if (o_rd_valid && i_rd_ready) begin
            o_rd_valid <= 1'b0;
        end
    end
endmodule
